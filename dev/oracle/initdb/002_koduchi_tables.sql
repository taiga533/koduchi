-- 週次のロールアップ。デザインのサンプルクエリが参照するビュー。
CREATE OR REPLACE VIEW koduchi.session_rollup AS
SELECT
  TRUNC(e.created_at, 'IW')                              AS week,
  e.channel                                              AS channel,
  COUNT(DISTINCT e.user_id)                              AS users,
  ROUND(AVG(e.duration_ms) / 1000, 2)                    AS avg_seconds,
  COUNT(*)                                               AS events
FROM koduchi.events e
GROUP BY TRUNC(e.created_at, 'IW'), e.channel;

-- スキーマツリーの「関数」枝を空にしないためのもの。
CREATE OR REPLACE FUNCTION koduchi.order_total(p_order_id IN NUMBER) RETURN NUMBER IS
  v_total NUMBER;
BEGIN
  SELECT NVL(SUM(qty * unit_price), 0)
    INTO v_total
    FROM koduchi.order_items
   WHERE order_id = p_order_id;
  RETURN v_total;
END;
/

-- DBMS_OUTPUT の確認用。メッセージタブが通知を拾えることを試せる。
CREATE OR REPLACE PROCEDURE koduchi.say_hello(p_times IN NUMBER DEFAULT 3) IS
BEGIN
