-- KODUCHI スキーマのテーブルとデータ（ADR 0010）。
--
-- 題材はデザインのサンプルクエリに揃えてある（events / orders / order_items /
-- refunds / user_traits / session_rollup）。デザインのクエリは PostgreSQL 方言で
-- 書かれているため、ここでは Oracle 方言に置き換えている。
--
-- EVENTS は 50,000 行を入れる。結果セットのカーソル分割取得（ADR 0003）が
-- 1,000 行ずつであるため、複数チャンクにまたがる表が 1 つ必要になる。

WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF
SET ECHO ON

ALTER SESSION SET CONTAINER = FREEPDB1;

-- 利用者。
CREATE TABLE koduchi.users (
  user_id     NUMBER(12)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email       VARCHAR2(255)   NOT NULL UNIQUE,
  display_name VARCHAR2(120),
  signed_up_at TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
  country     VARCHAR2(2)
);

-- 利用者の属性。デザインの update 文が対象にしている表。
CREATE TABLE koduchi.user_traits (
  user_id      NUMBER(12) PRIMARY KEY REFERENCES koduchi.users (user_id),
  segment      VARCHAR2(32),
  sessions_28d NUMBER(8) DEFAULT 0 NOT NULL,
  updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- イベント。行数が多い表。
CREATE TABLE koduchi.events (
  event_id   NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER(12)    NOT NULL,
  channel    VARCHAR2(32)  NOT NULL,
  event_name VARCHAR2(64)  NOT NULL,
  created_at TIMESTAMP     NOT NULL,
  duration_ms NUMBER(10)
);

CREATE TABLE koduchi.orders (
  order_id   NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    NUMBER(12)    NOT NULL,
  status     VARCHAR2(16)  NOT NULL,
  amount     NUMBER(12, 2) NOT NULL,
  currency   CHAR(3)       DEFAULT 'JPY' NOT NULL,
  created_at TIMESTAMP     NOT NULL
);

CREATE TABLE koduchi.order_items (
  order_item_id NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      NUMBER(12)    NOT NULL REFERENCES koduchi.orders (order_id),
  sku           VARCHAR2(32)  NOT NULL,
  qty           NUMBER(6)     NOT NULL,
  unit_price    NUMBER(12, 2) NOT NULL
);

CREATE TABLE koduchi.refunds (
  refund_id  NUMBER(12)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id   NUMBER(12)    NOT NULL REFERENCES koduchi.orders (order_id),
  amount     NUMBER(12, 2) NOT NULL,
  reason     VARCHAR2(200),
  created_at TIMESTAMP     NOT NULL
);

CREATE INDEX koduchi.ix_events_created ON koduchi.events (created_at);
CREATE INDEX koduchi.ix_events_user ON koduchi.events (user_id);
CREATE INDEX koduchi.ix_orders_user ON koduchi.orders (user_id);

